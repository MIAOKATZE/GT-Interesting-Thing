def shift(table: list[tuple], delta: int) -> list[tuple]:
    """整表环形相位偏移：只把「哪一帧最陡」挪走，不改变位点之间的相对节奏。

    用途：某态闪光位铺满后，帧 7->0 的接缝步变可能恰好是环内最大（视觉上表现为每 8 帧
    抽一下）。逐位调相会破坏 SHARED 表的两态同位纪律，故对最密的那一态整表偏移。
    """
    return [(x, y, (p + delta) % FRAMES, dim, on) for (x, y, p, dim, on) in table]

