    for y, (lo, hi) in spans.items():
        cells = _f4_row(lo, hi, y in F4_DARK_ROWS, y in F4_LIT_ROWS,
                        y in F4_LIT_WIDE_ROWS)
        for i, x in enumerate(range(lo, hi + 1)):
            grid[y][x] = cells[i]
    # 奖牌（12x12：外圈青铜 + 内暗格 + 金脸 + 受光档；四角切掉露布面 -> 不贴死成方块）
    mx, my = F4_MEDAL_TL
    for y in range(F4_MEDAL_H):
        for x in range(F4_MEDAL_W):
            if (x, y) in F4_MEDAL_CUT:
                continue
            ring = x in (0, F4_MEDAL_W - 1) or y in (0, F4_MEDAL_H - 1)
            grid[my + y][mx + x] = F4_MEDAL_RING if ring else F4_MEDAL_PLATE
    for y, row in enumerate(F4_FACE):
        for x, c in enumerate(row):
            if c != ".":
                grid[my + 1 + y][mx + 1 + x] = c
    for y, row in enumerate(F4_FACE_HL):
        for x, c in enumerate(row):
            if c != "." and grid[my + 1 + y][mx + 1 + x] in ("m",):
                grid[my + 1 + y][mx + 1 + x] = c
    detail = dict(F4_DETAIL_NORMAL)
    if open_state:
        detail.update(F4_DETAIL_OPEN)
    for (x, y), c in detail.items():
        grid[y][x] = c
    return ["".join(r) for r in grid]


