def frame_rows(fam: dict, state: str, f: int) -> list[str]:
    """第 f 帧 = 该态底形 + 只在登记位换档（工作态包络半宽更大 -> 同刻亮的位更多）。"""
    grid = [list(r) for r in grid_of(fam, state)]
    half = half_of(state)
    for (x, y, peak, dim, on) in fam["spark"][state]:
        lvl = env(f, peak, half=half)
        if lvl == 2:
            grid[y][x] = on
        elif lvl == 1:
            grid[y][x] = dim
    return ["".join(r) for r in grid]


