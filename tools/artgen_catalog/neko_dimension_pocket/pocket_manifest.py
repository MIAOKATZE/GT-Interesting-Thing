def env(frame: int, peak: int, period: int = FRAMES, half: int = SPARK_HALF) -> int:
    """第 frame 帧、峰值为 peak 的档位：0=off / 1=半亮 / 2=满亮（环形 -> 天然无缝）。"""
    d = (frame - peak) % period
    d = min(d, period - d)
    return max(0, half - d)


