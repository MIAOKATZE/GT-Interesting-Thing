def _f4_row(lo: int, hi: int, dark: bool, lit: bool, lit_wide: bool = False) -> list[str]:
    n = hi - lo + 1
    row = []
    for i in range(n):
        if i == 0 or i == n - 1:
            c = "#"
        elif i in (1, 2) and lit and (lit_wide or i == 1):
            c = F4_EDGE_LIT
        elif i == n - 2:
            c = F4_EDGE_VOID
        elif i >= n - 4:
            c = F4_EDGE_DK
        else:
            c = F4_MID
        if dark:
            c = F4_DARK_SHIFT[c]
        row.append(c)
    return row


